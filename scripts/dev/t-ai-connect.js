const { chromium } = require('playwright')
const S = process.env.OUT ?? '/tmp'; const DOCS = process.env.DOCS ?? '/tmp/mockdocs'
;(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1194, height: 834 }, locale: 'ko-KR' })
  const errs = []; p.on('pageerror', (e) => errs.push(e.message.slice(0, 150)))
  await p.goto('http://localhost:8766/index.html'); await p.waitForTimeout(2000)
  await p.locator('#homePane button.card.docs').click(); await p.waitForTimeout(7000)
  const f = p.frameLocator('iframe.pane:not([hidden])')
  console.log('panel:', (await f.locator('.ai-dock').innerText()).replace(/\s+/g, ' ').slice(0, 220))
  await p.screenshot({ path: S + '/ai-panel-gemini.png' })
  // the panel's settings button -> AI 연결 page
  const btn = f.locator('.ai-dock button', { hasText: /설정/ }).first()
  console.log('panel button:', await btn.innerText().catch(() => 'none'))
  await btn.click().catch((e) => console.log('click failed', e.message.slice(0, 80))); await p.waitForTimeout(1200)
  console.log('settings open:', await p.locator('#settingsPane').isVisible(), '| AI section:', (await p.locator('#settingsPane .ai-status').innerText().catch(() => '-')))
  await p.screenshot({ path: S + '/ai-connect.png' })
  await p.locator('.ai-card', { hasText: 'Claude' }).click(); await p.waitForTimeout(200)
  await p.locator('.ai-form input[type=password]').fill('sk-ant-api03-test'); await p.locator('.ai-form .ai-link', { hasText: '연결 확인' }).click(); await p.waitForTimeout(4000)
  console.log('check:', await p.locator('.ai-form p.hint').first().innerText())
  await p.locator('.ai-card', { hasText: 'Gemini' }).click(); await p.locator('.ai-form input[type=password]').fill('AIza-test-key'); await p.locator('.ai-form button.primary').click(); await p.waitForTimeout(1500)
  console.log('status after save:', await p.locator('.ai-status').innerText())
  console.log('stored:', require('fs').readFileSync(DOCS + '-support/ai-settings.json', 'utf8').match(/"provider": "[^"]+"|AIza-test-key/g))
  await p.screenshot({ path: S + '/ai-connect-saved.png' })
  console.log('errors', errs); await b.close() })()
