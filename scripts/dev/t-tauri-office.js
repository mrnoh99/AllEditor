const { chromium } = require('playwright')
const S = process.env.OUT ?? '/tmp'
;(async () => {
  const b = await chromium.launch()
  const pg = await b.newPage({ viewport: { width: 1180, height: 820 } })
  const errs = []
  pg.on('pageerror', (e) => errs.push('PAGE ' + e.message.slice(0, 160)))
  pg.on('console', (m) => { if (m.type() === 'error') errs.push('CON ' + m.text().slice(0, 160)) })
  await pg.goto('http://localhost:5190/index.html')
  await pg.waitForSelector('[data-testid=home-office-section]', { timeout: 20000 })
  await pg.screenshot({ path: S + '/tauri-home.png' })
  await pg.click('[data-testid=home-office-new-docs]')
  await pg.waitForSelector('[data-testid=office-overlay] iframe')
  const of = pg.frameLocator('[data-testid=office-overlay] iframe')
  await of.locator('#tabs .tab.docs.on').waitFor({ timeout: 30000 })
  const inner = of.frameLocator('iframe.pane:not([hidden])')
  await inner.locator('text=파일').first().waitFor({ timeout: 40000 })
  await pg.waitForTimeout(3000)
  await pg.screenshot({ path: S + '/tauri-office-docs.png' })
  // back to the home tab of the suite: list shows the seeded docx (read through /__ae readdir)
  await of.locator('#tabs .tab .tl', { hasText: '홈' }).click()
  await pg.waitForTimeout(800)
  console.log('suite home files:', (await of.locator('#homePane').innerText()).replace(/\s+/g, ' ').slice(0, 300))
  // back button -> overlay hidden
  await of.locator('#tabs .tl.back').click()
  await pg.waitForTimeout(500)
  console.log('overlay visible after back:', await pg.locator('[data-testid=office-overlay]').isVisible())
  // reopen: same iframe, tabs kept
  await pg.click('[data-testid=home-office-open]')
  await pg.waitForTimeout(500)
  console.log('tabs after reopen:', (await of.locator('#tabs').innerText()).replace(/\s+/g, ' '))
  console.log('native log:', await (await fetch('http://localhost:8766/__log')).text())
  console.log(errs.length + ' errors'); [...new Set(errs)].slice(0, 12).forEach((e) => console.log('  ', e))
  await b.close()
})()
