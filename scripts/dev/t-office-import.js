const { chromium } = require('playwright'); const fs = require('fs')
;(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1180, height: 820 } })
  const errs = []; p.on('pageerror', (e) => errs.push(e.message.slice(0, 160)))
  await p.goto('http://localhost:5190/host.html')
  await p.waitForFunction(() => window.__last?.type === 'ae-office-ready', null, { timeout: 30000 })
  const data = fs.readFileSync('/home/user/AllEditor/scripts/dev/fixtures/t.pptx').toString('base64')
  await p.evaluate((d) => document.getElementById('f').contentWindow.postMessage({ type: 'ae-office', action: 'import', name: '메일첨부.pptx', data: d }, '*'), data)
  await p.waitForTimeout(6000)
  const f = p.frameLocator('#f')
  console.log('tabs:', (await f.locator('#tabs').innerText()).replace(/\s+/g, ' '))
  console.log('stored:', fs.readdirSync(process.argv[2]).join(', '))
  console.log('errors', errs)
  await b.close()
})()
