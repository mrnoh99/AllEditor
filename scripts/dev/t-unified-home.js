const { chromium } = require('playwright')
const S = process.env.OUT ?? '/tmp'
;(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1194, height: 834 }, locale: 'ko-KR' })
  const errs = []; p.on('pageerror', (e) => errs.push(e.message.slice(0, 150)))
  const msgs = []; await p.exposeFunction('__note', (m) => msgs.push(m))
  await p.addInitScript(() => window.addEventListener('message', (e) => { if (e.data?.type?.startsWith?.('ae-')) window.__note(JSON.stringify(e.data)) }))
  await p.goto('http://localhost:5190/index.html'); await p.waitForTimeout(2500)
  await p.screenshot({ path: S + '/unified-home.png' })
  console.log('cards:', await p.locator('[data-testid=home-unified] .mobile-quick-card-title').allInnerTexts())
  console.log('md button gone:', await p.locator('[data-testid=home-new-md-btn]').count() === 0)
  await p.click('[data-testid=home-library]'); await p.waitForTimeout(4000)
  const f = p.frameLocator('[data-testid=office-overlay] iframe')
  console.log('library new cards:', (await f.locator('#homePane .grid').innerText()).replace(/\s+/g, ' '))
  console.log('library hwpx label:', (await f.locator('#homePane .files').innerText()).match(/한글\s+t\.hwpx/)?.[0])
  await f.locator('#homePane .files >> text=t.hwpx').first().click(); await p.waitForTimeout(800)
  console.log('overlay hidden after hwpx tap:', !(await p.locator('[data-testid=office-overlay]').isVisible()), '| host got:', msgs.filter((m) => m.includes('hwp')))
  console.log('errors', errs); await b.close() })()
