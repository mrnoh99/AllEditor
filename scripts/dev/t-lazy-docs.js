const { chromium } = require('playwright'); const { execSync } = require('child_process')
;(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1194, height: 834 }, locale: 'ko-KR' })
  const errs = []; p.on('pageerror', (e) => errs.push(e.message.slice(0, 150)))
  const rss = () => Math.round(Number(execSync("ps -eo rss,args | grep -E 'chrome.*--type=renderer' | grep -v grep | awk '{s+=$1} END {print s}'").toString()) / 1024)
  await p.goto('http://localhost:8766/index.html'); await p.waitForTimeout(3000)
  console.log('home list:', (await p.locator('#homePane .files').innerText()).replace(/\s+/g, ' ').slice(0, 260))
  console.log('RSS home', rss(), 'MB')
  await p.locator('#homePane .files >> text=t.xlsx').first().click(); await p.waitForTimeout(8000); console.log('RSS + small xlsx tab', rss(), 'MB')
  await p.locator('#tabs .tab .tl', { hasText: '홈' }).click(); await p.locator('#homePane .files >> text=big3.pptx').first().click(); await p.waitForTimeout(12000)
  const f = p.frameLocator('iframe.pane:not([hidden])')
  console.log('big3 opened:', (await f.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 80), '| RSS', rss(), 'MB')
  const log = JSON.parse(await (await fetch('http://localhost:8766/__log')).text()).filter((x) => /readFile big/.test(x))
  console.log('big files read natively:', log.length, [...new Set(log)].join(', '))
  console.log('errors', errs); await b.close() })()
