const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1194, height: 834 }, locale: 'ko-KR' })
  const dialogs = []; p.on('dialog', (d) => { dialogs.push(d.message()); d.dismiss() })
  await p.goto('http://localhost:8766/index.html'); await p.waitForTimeout(2500)
  console.log('credit:', await p.locator('#homePane .credit').innerText())
  await p.locator('#homePane .files >> text=t.pptx').first().click(); await p.waitForTimeout(7000)
  console.log('send button:', await p.locator('#tabs .send').innerText())
  await p.click('#tabs .send'); await p.waitForTimeout(1500)
  await p.locator('#tabs .tab .tl', { hasText: '홈' }).click(); await p.waitForTimeout(300)
  await p.locator('#homePane button.card.docs').click(); await p.waitForTimeout(6000)
  console.log('send button (new doc):', await p.locator('#tabs .send').innerText())
  await p.click('#tabs .send'); await p.waitForTimeout(800)
  await p.screenshot({ path: (process.env.OUT ?? '/tmp') + '/send.png' })
  console.log('dialogs:', dialogs)
  console.log('log:', JSON.parse(await (await fetch('http://localhost:8766/__log')).text()).filter((x) => x.startsWith('share')))
  await b.close()
})()
